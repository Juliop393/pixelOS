export function cleanDomains(text) {
  const protectedSet = new Set(PROTECTED_DOMAINS)
  const domains = new Set()
  let invalid = 0
  for (const raw of text.split(/\r?\n/)) {
    const domain = raw.trim().toLowerCase().replace(/\.$/, "")
    if (!domain || domain.startsWith("#")) continue
    if (!DOMAIN.test(domain) || domain.length > 253) { invalid += 1; continue }
    if (protectedSet.has(domain)) continue
    domains.add(domain)
  }
  return { domains: [...domains].sort(), invalid }
}

export function buildSql(domains) {
  const quote = (value) => `'${value.replace(/'/g, "''")}'`
  const chunks = []
  for (let i = 0; i < domains.length; i += 1000) {
    chunks.push(`INSERT INTO incoming_disposable_domains (domain) VALUES\n${domains.slice(i, i + 1000).map((d) => `(${quote(d)})`).join(",\n")};`)
  }
  return `-- Generated by scripts/update-disposable-domains.mjs on ${new Date().toISOString()}
-- Source: ${SOURCE_URL}
-- Domains: ${domains.length}. Replaces public.disposable_email_domains in one transaction.
\\set ON_ERROR_STOP on
BEGIN;
CREATE TEMP TABLE incoming_disposable_domains (domain TEXT PRIMARY KEY) ON COMMIT DROP;
${chunks.join("\n")}
DO $guard$
BEGIN
  IF (SELECT count(*) FROM incoming_disposable_domains) < ${MIN_DOMAINS} THEN
    RAISE EXCEPTION 'disposable list too small, refusing to replace it';
  END IF;
  IF EXISTS (SELECT 1 FROM incoming_disposable_domains WHERE domain IN (${PROTECTED_DOMAINS.map(quote).join(", ")})) THEN
    RAISE EXCEPTION 'disposable list contains a protected provider';
  END IF;
END
$guard$;
DELETE FROM public.disposable_email_domains d
 WHERE NOT EXISTS (SELECT 1 FROM incoming_disposable_domains i WHERE i.domain = d.domain);
INSERT INTO public.disposable_email_domains (domain)
SELECT domain FROM incoming_disposable_domains
ON CONFLICT (domain) DO NOTHING;
COMMIT;
`
}

async function main() {
  const [output, flag, file] = process.argv.slice(2)
  if (!output) {
    console.error("Usage: node scripts/update-disposable-domains.mjs <output.sql> [--file domains.txt]")
    process.exit(2)
  }
  let text
  if (flag === "--file" && file) {
    text = readFileSync(file, "utf8")
  } else {
    const response = await fetch(SOURCE_URL)
    if (!response.ok) throw new Error(`download failed: HTTP ${response.status}`)
    text = await response.text()
  }
  const { domains, invalid } = cleanDomains(text)
  if (domains.length < MIN_DOMAINS) throw new Error(`only ${domains.length} domains, refusing to write`)
  writeFileSync(output, buildSql(domains))
  console.log(`${domains.length} domains written to ${output} (${invalid} invalid lines skipped)`)
}

// Runs only when executed directly, so tests can import cleanDomains/buildSql.
if (process.argv[1]?.replaceAll("\\", "/").endsWith("scripts/update-disposable-domains.mjs")) {
  main().catch((error) => { console.error(error.message); process.exit(1) })
}
