#!/usr/bin/env node
/*
 * Builds the SQL that refreshes public.disposable_email_domains (migration 018).
 *
 *   node scripts/update-disposable-domains.mjs <output.sql> [--file domains.txt]
 *
 * Downloads domains.txt from disposable/disposable-email-domains once (never per sign-up), or
 * reads a local copy with --file. The "strict" list is deliberately not used: it contains
 * Outlook, Hotmail, Live, Proton and Tuta. Protected providers below are removed even if the
 * upstream list ever adds them, and the generated SQL re-checks them before committing.
 *
 * The output replaces the whole list in one transaction and refuses to commit if the new list
 * is suspiciously small (a broken download must never empty the table). Apply it with psql
 * against the database; it touches nothing but public.disposable_email_domains.
 * Suggested cadence: monthly.
 */
import { readFileSync, writeFileSync } from "node:fs"

const SOURCE_URL = "https://raw.githubusercontent.com/disposable/disposable-email-domains/master/domains.txt"
const MIN_DOMAINS = 50_000
const DOMAIN = /^[a-z0-9]([a-z0-9-]*[a-z0-9])?(\.[a-z0-9]([a-z0-9-]*[a-z0-9])?)+$/

// Legitimate providers and relay services that must never be blocked.
